import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync
} from 'node:fs';
import { basename, join, resolve } from 'node:path';

export interface AreaJson {
  id: string;
  cityId: string;
  provinceId: string;
  name: string;
  urduName?: string;
  aliases: string[];
  postalCode?: string;
  coordinates: {
    lat: number;
    lng: number;
  };
  type?: string;
  verified: boolean;
  sources?: unknown[];
}

export interface CityJson {
  id: string;
  name: string;
  urduName: string;
  provinceId: string;
  division?: string;
  district: string;
  coordinates: {
    lat: number;
    lng: number;
  };
  postalCodeRange?: [string, string];
  bounds?: {
    minLat: number;
    maxLat: number;
    minLng: number;
    maxLng: number;
  };
  totalAreasCount?: number;
}

export interface ProvinceJson {
  id: string;
  name: string;
  urduName: string;
  capitalCityId: string;
  type: string;
}

export interface CodegenResult {
  provincesCount: number;
  citiesCount: number;
  areasCount: number;
}

export function escapeDartString(str: string): string {
  return str
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\$/g, '\\$')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n');
}

export function formatDartNumber(n: number): string {
  return Number.isInteger(n) ? `${n}.0` : n.toString();
}

export function findJsonFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  const results: string[] = [];
  const entries = readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...findJsonFiles(fullPath));
    } else if (entry.isFile() && entry.name.endsWith('.json')) {
      results.push(fullPath);
    }
  }
  return results;
}

export async function generateDartData(
  dataDir: string,
  dartLibDir: string,
  cityAreaCounts: Record<string, number> = {}
): Promise<CodegenResult> {
  const srcDataDir = resolve(dartLibDir, 'src/data');
  mkdirSync(srcDataDir, { recursive: true });

  // 1. Provinces
  const provincesRaw = JSON.parse(
    readFileSync(resolve(dataDir, 'provinces.json'), 'utf-8')
  ) as ProvinceJson[];

  const provinceEntries = provincesRaw.map((p) => {
    return `  PakistanProvince(\n    id: '${escapeDartString(p.id)}',\n    name: '${escapeDartString(p.name)}',\n    urduName: '${escapeDartString(p.urduName)}',\n    capitalCityId: '${escapeDartString(p.capitalCityId)}',\n    type: '${escapeDartString(p.type)}',\n  )`;
  });

  const provincesDart = `// GENERATED CODE - DO NOT MODIFY BY HAND\n// Generated by scripts/codegen/dart.ts\n\nimport '../models.dart';\n\nconst pakistanProvinces = <PakistanProvince>[\n${provinceEntries.join(',\n')},\n];\n`;
  writeFileSync(resolve(srcDataDir, 'provinces.dart'), provincesDart, 'utf-8');
  const provincesCount = provincesRaw.length;

  // 2. Areas
  const areaFiles = findJsonFiles(resolve(dataDir, 'areas')).sort();
  const allAreas: AreaJson[] = [];

  for (const filePath of areaFiles) {
    const citySlug = basename(filePath, '.json');
    const content = JSON.parse(readFileSync(filePath, 'utf-8')) as AreaJson[];
    cityAreaCounts[citySlug] = content.length;
    allAreas.push(...content);
  }

  const areaEntries = allAreas.map((a) => {
    const fields: string[] = [
      `id: '${escapeDartString(a.id)}'`,
      `cityId: '${escapeDartString(a.cityId)}'`,
      `provinceId: '${escapeDartString(a.provinceId)}'`,
      `name: '${escapeDartString(a.name)}'`
    ];

    if (a.urduName !== undefined && a.urduName !== null) {
      fields.push(`urduName: '${escapeDartString(a.urduName)}'`);
    }

    const aliasesFormatted = (a.aliases || [])
      .map((al) => `'${escapeDartString(al)}'`)
      .join(', ');
    fields.push(`aliases: [${aliasesFormatted}]`);

    if (a.postalCode !== undefined && a.postalCode !== null) {
      fields.push(`postalCode: '${escapeDartString(a.postalCode)}'`);
    }

    fields.push(
      `coordinates: Coordinates(lat: ${formatDartNumber(a.coordinates.lat)}, lng: ${formatDartNumber(a.coordinates.lng)})`
    );

    if (a.type !== undefined && a.type !== null) {
      fields.push(`type: '${escapeDartString(a.type)}'`);
    }

    fields.push(`verified: ${a.verified ? 'true' : 'false'}`);

    return `  PakistanArea(\n    ${fields.join(',\n    ')},\n  )`;
  });

  const areasDart = `// GENERATED CODE - DO NOT MODIFY BY HAND\n// Generated by scripts/codegen/dart.ts\n\nimport '../models.dart';\n\nconst pakistanAreas = <PakistanArea>[\n${areaEntries.join(',\n')},\n];\n`;
  writeFileSync(resolve(srcDataDir, 'areas.dart'), areasDart, 'utf-8');
  const areasCount = allAreas.length;

  // 3. Cities with totalAreasCount
  const cityFiles = readdirSync(resolve(dataDir, 'cities'))
    .filter((f) => f.endsWith('.json'))
    .sort();

  const allCities: CityJson[] = [];
  for (const f of cityFiles) {
    const citiesInFile = JSON.parse(
      readFileSync(resolve(dataDir, 'cities', f), 'utf-8')
    ) as CityJson[];
    for (const city of citiesInFile) {
      allCities.push({
        ...city,
        totalAreasCount: cityAreaCounts[city.id] || 0
      });
    }
  }

  const cityEntries = allCities.map((c) => {
    const fields: string[] = [
      `id: '${escapeDartString(c.id)}'`,
      `name: '${escapeDartString(c.name)}'`,
      `urduName: '${escapeDartString(c.urduName)}'`,
      `provinceId: '${escapeDartString(c.provinceId)}'`
    ];

    if (c.division !== undefined && c.division !== null) {
      fields.push(`division: '${escapeDartString(c.division)}'`);
    }

    fields.push(`district: '${escapeDartString(c.district)}'`);
    fields.push(
      `coordinates: Coordinates(lat: ${formatDartNumber(c.coordinates.lat)}, lng: ${formatDartNumber(c.coordinates.lng)})`
    );

    if (c.postalCodeRange) {
      fields.push(
        `postalCodeRange: ['${escapeDartString(c.postalCodeRange[0])}', '${escapeDartString(c.postalCodeRange[1])}']`
      );
    }

    if (c.bounds) {
      fields.push(
        `bounds: CityBounds(minLat: ${formatDartNumber(c.bounds.minLat)}, maxLat: ${formatDartNumber(c.bounds.maxLat)}, minLng: ${formatDartNumber(c.bounds.minLng)}, maxLng: ${formatDartNumber(c.bounds.maxLng)})`
      );
    }

    fields.push(`totalAreasCount: ${c.totalAreasCount ?? 0}`);

    return `  PakistanCity(\n    ${fields.join(',\n    ')},\n  )`;
  });

  const citiesDart = `// GENERATED CODE - DO NOT MODIFY BY HAND\n// Generated by scripts/codegen/dart.ts\n\nimport '../models.dart';\n\nconst pakistanCities = <PakistanCity>[\n${cityEntries.join(',\n')},\n];\n`;
  writeFileSync(resolve(srcDataDir, 'cities.dart'), citiesDart, 'utf-8');
  const citiesCount = allCities.length;

  return {
    provincesCount,
    citiesCount,
    areasCount
  };
}
